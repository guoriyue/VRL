logger = logging.getLogger(__name__)


@dataclass(frozen=True, slots=True)
class CheckpointTarget:
    """One checkpoint label/path pair from the CLI."""

    label: str
    path: Path


@dataclass(frozen=True, slots=True)
class GeneratedVideo:
    """Materialized video generated by one checkpoint for one prompt/sample."""

    checkpoint_label: str
    prompt_index: int
    sample_index: int
    seed: int
    prompt: str
    path: Path


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Generate the same prompt/seed grid from Cosmos Predict2.5 checkpoints "
            "and score the resulting videos with Kling VideoReward."
        ),
    )
    parser.add_argument(
        "--config",
        default="experiment/cosmos_predict2_5/online_nft_kling_video_reward",
        help="Bundled config name or absolute YAML path.",
    )
    parser.add_argument(
        "--checkpoint",
        action="append",
        required=True,
        help="Checkpoint dir or label=checkpoint-dir. Repeat for baseline and trained checkpoints.",
    )
    parser.add_argument("--prompt", action="append", default=[], help="Prompt to evaluate.")
    parser.add_argument("--manifest", default="", help="Prompt manifest to evaluate.")
    parser.add_argument(
        "--eval-manifest",
        action="store_true",
        help="Use cfg.data.eval_manifest, falling back to cfg.data.manifest.",
    )
    parser.add_argument("--limit", type=int, default=0, help="Maximum prompts to evaluate.")
    parser.add_argument("--samples-per-prompt", type=int, default=2)
    parser.add_argument("--seed", type=int, default=20260614)
    parser.add_argument("--output-dir", default="outputs/cosmos_predict25_kling_eval")
    parser.add_argument("--width", type=int, default=0)
    parser.add_argument("--height", type=int, default=0)
    parser.add_argument("--num-frames", type=int, default=0)
    parser.add_argument("--steps", type=int, default=0)
    parser.add_argument("--fps", type=int, default=0)
    parser.add_argument("--max-sequence-length", type=int, default=0)
    parser.add_argument("--guidance-scale", type=float, default=None)
    parser.add_argument(
        "--score-key",
        default="",
        help="Reward score key; defaults to reward.kwargs.kling_video_reward.score_key.",
    )
    parser.add_argument(
        "--device",
        default="auto",
        help="Torch device. Defaults to cuda:0 when CUDA is available, else cpu.",
    )
    parser.add_argument(
        "--dtype",
        choices=("auto", "fp32", "float32", "fp16", "float16", "bf16", "bfloat16"),
        default="auto",
    )
    parser.add_argument(
        "--generate-only",
        action="store_true",
        help="Generate mp4s and metadata without loading Kling VideoReward.",
    )
    parser.add_argument(
        "--rebuild-model-between-checkpoints",
        action="store_true",
        help="Rebuild the full generation model before every checkpoint.",
    )
    parser.add_argument("overrides", nargs="*", help="OmegaConf dotlist overrides.")
    return parser


def main(argv: list[str] | None = None) -> None:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    args = build_parser().parse_args(argv)
    if args.samples_per_prompt < 1:
        raise ValueError("--samples-per-prompt must be >= 1")
    if args.limit < 0:
        raise ValueError("--limit must be >= 0")
    keep_model_between_checkpoints = not args.rebuild_model_between_checkpoints

    cfg = load_config(args.config, overrides=args.overrides)
    root = parse_config(cfg)
    precision = resolve_precision_policy(root)
    prompts = _load_prompts(args, cfg)
    if args.limit:
        prompts = prompts[: args.limit]
    if not prompts:
        raise ValueError("provide --prompt, --manifest, or --eval-manifest")
    checkpoint_targets = _parse_checkpoint_targets(args.checkpoint)

    device = resolve_eval_device(args.device)
    dtype = _resolve_dtype(
        args.dtype,
        root,
        precision=precision,
        device=device,
    )
    sampling = _resolve_sampling(args, cfg)
    if root.model is None:
        raise ValueError("Cosmos checkpoint evaluation requires model configuration")
    entry = get_model_family_entry(str(root.model.family))
    build = entry.resolve_model_build(
        root,
        device,
        precision=precision,
        parameter_dtype_override=dtype,
    )
    model_identity = resolve_checkpoint_model_identity(build)
    for target in checkpoint_targets:
        checkpoint_dir = target.path.parent if target.path.is_file() else target.path
        validate_checkpoint_meta_compatibility(
            read_checkpoint_meta(checkpoint_dir),
            family=entry.family,
            expected_model_identity=model_identity,
            strict=True,
        )
    output_dir = Path(args.output_dir).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    run_config = {
        "config": args.config,
        "checkpoints": [
            {"label": target.label, "path": str(target.path)} for target in checkpoint_targets
        ],
        "prompt_count": len(prompts),
        "samples_per_prompt": int(args.samples_per_prompt),
        "seed": int(args.seed),
        "sampling": sampling,
        "score_key": _score_key(args, cfg),
        "keep_model_between_checkpoints": keep_model_between_checkpoints,
    }
    (output_dir / "run_config.json").write_text(
        json.dumps(run_config, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )

    generated = _generate_all(
        build,
        checkpoint_targets,
        prompts,
        samples_per_prompt=int(args.samples_per_prompt),
        base_seed=int(args.seed),
        output_dir=output_dir,
        sampling=sampling,
        keep_model_between_checkpoints=keep_model_between_checkpoints,
        expected_model_identity=model_identity,
    )
    _write_generation_metadata(generated, output_dir)

    if args.generate_only:
        print(json.dumps({"output_dir": str(output_dir), "videos": len(generated)}, indent=2))
        return

    score_key = _score_key(args, cfg)
    rows = _score_generated_videos(generated, cfg, score_key=score_key)
    _write_scores(rows, output_dir)
    summary = _summarize_scores(rows)
    (output_dir / "summary.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(json.dumps({"output_dir": str(output_dir), "summary": summary}, indent=2))


def _load_prompts(args: argparse.Namespace, cfg: DictConfig) -> list[str]:
    prompts = [str(prompt).strip() for prompt in args.prompt if str(prompt).strip()]
    if args.eval_manifest:
        manifest = str(OmegaConf.select(cfg, "data.eval_manifest", default=cfg.data.manifest))
        prompts.extend(example.prompt for example in load_prompt_manifest(manifest))
    if args.manifest:
        prompts.extend(example.prompt for example in load_prompt_manifest(args.manifest))
    return prompts


def _parse_checkpoint_targets(values: list[str]) -> list[CheckpointTarget]:
    targets = [_parse_checkpoint_target(value) for value in values]
    labels = [target.label for target in targets]
    if len(set(labels)) != len(labels):
        raise ValueError(f"checkpoint labels must be unique: {labels}")
    return targets


def _parse_checkpoint_target(value: str) -> CheckpointTarget:
    text = str(value).strip()
    if not text:
        raise ValueError("--checkpoint values must be non-empty")
    if "=" in text:
        label, raw_path = text.split("=", 1)
        label = _normalize_checkpoint_label(label)
        path = Path(raw_path).expanduser().resolve()
    else:
        path = Path(text).expanduser().resolve()
        label = _normalize_checkpoint_label(
            path.parent.name if path.name == "checkpoint-final" else path.name,
        )
    if not label:
        raise ValueError(f"checkpoint label resolved empty for {value!r}")
    if not path.exists():
        raise FileNotFoundError(f"checkpoint path does not exist: {path}")
    return CheckpointTarget(label=label, path=path)


def _normalize_checkpoint_label(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", str(value).strip()).strip("._-")


def _resolve_dtype(
    dtype_arg: str,
    root: RootConfig,
    *,
    precision: PrecisionPolicy,
    device: torch.device,
) -> torch.dtype:
    if dtype_arg != "auto":
        return resolve_torch_dtype(dtype_arg)
    if root.trainer is None:
        raise ValueError("Cosmos checkpoint evaluation requires an online trainer config")
    dtype = resolve_torch_dtype(precision.training.dtype)
    if getattr(device, "type", str(device)) == "cpu":
        return torch.float32
    return dtype


def _resolve_sampling(args: argparse.Namespace, cfg: DictConfig) -> dict[str, Any]:
    # Adapt this script's CLI flags to the shared sampling projection. The arg names
    # (notably --steps -> num_steps) are cosmos-specific; wan has no such overrides.
    return resolve_eval_sampling(
        cfg,
        overrides={
            "width": args.width,
            "height": args.height,
            "num_frames": args.num_frames,
            "num_steps": args.steps,
            "fps": args.fps,
            "max_sequence_length": args.max_sequence_length,
            "guidance_scale": args.guidance_scale,
        },
    )


def _generate_all(
    build: Any,
    checkpoint_targets: list[CheckpointTarget],
    prompts: list[str],
    *,
    samples_per_prompt: int,
    base_seed: int,
    output_dir: Path,
    sampling: dict[str, Any],
    keep_model_between_checkpoints: bool,
    expected_model_identity: dict[str, Any],
) -> list[GeneratedVideo]:
    generated: list[GeneratedVideo] = []
    bundle: Any | None = None
    entry = get_model_family_entry(str(build.family))
    try:
        for target in checkpoint_targets:
            if bundle is None or not keep_model_between_checkpoints:
                release_cuda_memory()
                logger.info(
                    "Building Cosmos Predict2.5 generation bundle for %s",
                    target.label,
                )
                bundle = entry.build_rollout(build)
                if resolve_checkpoint_model_identity(build) != expected_model_identity:
                    raise RuntimeError(
                        "Cosmos model source changed during runtime construction",
                    )
            logger.info("Loading checkpoint-owned state from %s", target.path)
            training_checkpoint = load_training_checkpoint(target.path)
            restore_model_checkpoint(
                training_checkpoint,
                bundle=bundle,
                family=entry.family,
                expected_model_identity=expected_model_identity,
                strict=True,
            )
            model = bundle.model.eval()
            try:
                generated.extend(
                    _generate_checkpoint_videos(
                        model,
                        target,
                        prompts,
                        samples_per_prompt=samples_per_prompt,
                        base_seed=base_seed,
                        output_dir=output_dir,
                        sampling=sampling,
                    ),
                )
            finally:
                del model
            if not keep_model_between_checkpoints:
                del bundle
                bundle = None
                release_cuda_memory()
    finally:
        del bundle
        release_cuda_memory()
    return generated


def _generate_checkpoint_videos(
    model: Any,
    target: CheckpointTarget,
    prompts: list[str],
    *,
    samples_per_prompt: int,
    base_seed: int,
    output_dir: Path,
    sampling: dict[str, Any],
) -> list[GeneratedVideo]:
    videos: list[GeneratedVideo] = []
    video_dir = output_dir / "videos" / target.label
    video_dir.mkdir(parents=True, exist_ok=True)
    for prompt_index, prompt in enumerate(prompts):
        for sample_index in range(samples_per_prompt):
            seed = _seed_for(
                base_seed=base_seed,
                prompt_index=prompt_index,
                sample_index=sample_index,
                samples_per_prompt=samples_per_prompt,
            )
            logger.info(
                "Generating checkpoint=%s prompt=%d sample=%d seed=%d",
                target.label,
                prompt_index,
                sample_index,
                seed,
            )
            tensor = _generate_one_video(
                model,
                prompt=prompt,
                seed=seed,
                sampling=sampling,
            )
            path = video_dir / f"prompt{prompt_index:04d}_sample{sample_index:02d}.mp4"
            write_mp4(tensor, path, fps=float(sampling["fps"]))
            videos.append(
                GeneratedVideo(
                    checkpoint_label=target.label,
                    prompt_index=prompt_index,
                    sample_index=sample_index,
                    seed=seed,
                    prompt=prompt,
                    path=path.resolve(),
                ),
            )
    return videos


# Generation helpers live in the shared denoise_video_generation module (wan reuses
# generate_one_video too). Keep the private names as aliases so the call sites above
# and the pinned test refs (eval_script._seed_for / _video_to_cthw) keep resolving.
_seed_for = seed_for
_generate_one_video = generate_one_video
_video_to_cthw = video_to_cthw


def _score_generated_videos(
    generated: list[GeneratedVideo],
    cfg: DictConfig,
    *,
    score_key: str,
) -> list[dict[str, Any]]:
    worker_config = resolve_kling_worker_config(cfg)
    logger.info("Loading Kling VideoReward for %d videos", len(generated))
    model = KlingVideoRewardModel(worker_config)
    request = RewardInferenceRequest(
        request_id="cosmos-predict25-controlled-eval",
        artifacts=tuple(
            RewardInferenceArtifact(
                artifact_id=_artifact_id(video),
                path=str(video.path),
                prompt=video.prompt,
                metadata={
                    "checkpoint_label": video.checkpoint_label,
                    "seed": video.seed,
                },
            )
            for video in generated
        ),
    )
    rows: list[dict[str, Any]] = []
    try:
        for artifact, video in zip(request.artifacts, generated, strict=True):
            scores = model(artifact)
            selected_keys = tuple(key.strip() for key in score_key.split("+") if key.strip())
            rows.append(
                {
                    "checkpoint_label": video.checkpoint_label,
                    "prompt_index": video.prompt_index,
                    "sample_index": video.sample_index,
                    "seed": video.seed,
                    "prompt": video.prompt,
                    "video_path": str(video.path),
                    "selected_score": sum(float(scores[key]) for key in selected_keys),
                    **{f"score_{key}": value for key, value in scores.items()},
                },
            )
    finally:
        del model
        release_cuda_memory()
    return rows


def _score_key(args: argparse.Namespace, cfg: DictConfig) -> str:
    return str(
        args.score_key
        or OmegaConf.select(
            cfg,
            "reward.kwargs.kling_video_reward.score_key",
            default="overall_reward",
        ),
    )


def _artifact_id(video: GeneratedVideo) -> str:
    return f"{video.checkpoint_label}-p{video.prompt_index:04d}-s{video.sample_index:02d}"


def _write_generation_metadata(videos: list[GeneratedVideo], output_dir: Path) -> None:
    path = output_dir / "generated.jsonl"
    with path.open("w", encoding="utf-8") as handle:
        for video in videos:
            row = asdict(video)
            row["path"] = str(video.path)
            handle.write(json.dumps(row, sort_keys=True) + "\n")


def _write_scores(rows: list[dict[str, Any]], output_dir: Path) -> None:
    jsonl_path = output_dir / "scores.jsonl"
    with jsonl_path.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, sort_keys=True) + "\n")
    csv_path = output_dir / "scores.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        fieldnames = sorted({key for row in rows for key in row})
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def _summarize_scores(rows: list[dict[str, Any]]) -> dict[str, Any]:
    grouped: dict[str, list[float]] = {}
    for row in rows:
        grouped.setdefault(str(row["checkpoint_label"]), []).append(float(row["selected_score"]))
    summary: dict[str, Any] = {}
    for label, values in grouped.items():
        tensor = torch.tensor(values, dtype=torch.float64)
        summary[label] = {
            "count": len(values),
            "mean": float(tensor.mean().item()),
            "std": float(tensor.std(unbiased=False).item()) if len(values) > 1 else 0.0,
            "min": float(tensor.min().item()),
            "max": float(tensor.max().item()),
        }
    return summary


if __name__ == "__main__":
    main()
